def main():
    # 一次读完每份文件，逐条核锚点
    texts = {}
    bad = 0
    for path, a, _n, label in ANCHORS:
        if path not in texts:
            texts[path] = io.open(path, encoding="utf-8").read()
        n = texts[path].count(a)
        print(u"  锚点 %-32s 命中 %d 次" % (label, n))
        if n != 1:
            bad += 1
    if bad:
        print(u"!! 有锚点不唯一，一个字节都不写")
        return 1
    for path, a, n, label in ANCHORS:
        texts[path] = texts[path].replace(a, n, 1)
        print(u"  [OK]   %s 已插入" % label)
    for path, text in texts.items():
        io.open(path, "w", encoding="utf-8", newline=u"\n").write(text)
        print(u"  写回 %s（%d 字节）" % (path, len(text)))
    return 0



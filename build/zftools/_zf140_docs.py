def patch(text, anchor, insert, tag, before=True):
    n = text.count(anchor)
    assert n == 1, u"锚点[%s]命中 %d 次" % (tag, n)
    return text.replace(anchor, (insert + anchor) if before else (anchor + insert), 1)



def main():
    text = io.open(DOC, encoding="utf-8").read()
    before = len(text)
    problems = []

    lines = text.split(u"\n")
    out = []
    added = False
    for line in lines:
        out.append(line)
        if line.startswith(u"| ZF67 |") and not added:
            out.append(ROW)
            added = True
    if not added:
        problems.append(u"没找到 ZF67 行")
    text = u"\n".join(out)

    for name, old, new in ((u"§9 ZF67 尾", OLD9, NEW9),
                           (u"§12.15 ZF56 段", J_ANCHOR, J_INSERT),
                           (u"§5 标题锚点", M_ANCHOR, M_INSERT + M_ANCHOR)):
        n = text.count(old)
        if n != 1:
            problems.append(u"%s 命中 %d 次（应为 1）" % (name, n))
        else:
            text = text.replace(old, new, 1)

    if problems:
        print(u"有失败项，**不落盘**：")
        for p in problems:
            print(u"  !! " + p)
        return 1

    io.open(DOC, "w", encoding="utf-8", newline="\n").write(text)
    print(u"字数 %d -> %d（+%d）" % (before, len(text), len(text) - before))
    print(u"§5 ZF68 行（成品 %s）+ §9 两条 + §4.40 + §12.15 更新 已写入" % SHA[:8])
    return 0


if __name__ == "__main__":
    sys.exit(main())
